/// The rows of `c`'s glyph; a character outside the font shows as `?`.
pub fn glyph(c: char) -> &'static [u8; 8] {
    let index = match c {
        ' '..='~' => c as usize - 32,
        CHECK => 95,
        CROSS => 96,
        _ => usize::from(b'?' - 32),
    };
    &GLYPHS[index]
}

/// The width `text` takes, in pixels.
pub fn width(text: &str) -> i32 {
    text.chars().count() as i32 * ADVANCE
}

/// Draw `text` with its top-left at `origin`, each glyph pixel a
/// `scale` x `scale` square, clipped to the image; returns the pen's end.
pub fn draw_scaled(
    image: &mut IndexedImage,
    origin: [i32; 2],
    text: &str,
    color: u8,
    scale: i32,
) -> i32 {
    let [mut pen, top] = origin;
    for c in text.chars() {
        for (row, bits) in (0..).zip(glyph(c)) {
            for column in 0..5 {
                if bits & (0x10 >> column) != 0 {
                    image.fill_rect(
                        [pen + column * scale, top + row * scale, scale, scale],
                        color,
                    );
                }
            }
        }
        pen += ADVANCE * scale;
    }
    pen
}

pub fn draw(image: &mut IndexedImage, origin: [i32; 2], text: &str, color: u8) -> i32 {
    draw_scaled(image, origin, text, color, 1)
}

/// `text` cut to `columns` glyphs, keeping its end (a path's file name)
/// behind a leading `..` when it is too long.
pub fn clip_start(text: &str, columns: usize) -> String {
    let count = text.chars().count();
    if count <= columns {
        return text.to_owned();
    }
    let keep = columns.saturating_sub(2);
    let tail: String = text.chars().skip(count - keep).collect();
    format!("..{tail}")
}

/// `text` cut to `columns` glyphs, keeping its start.
pub fn clip_end(text: &str, columns: usize) -> String {
    if text.chars().count() <= columns {
        return text.to_owned();
    }
    let head: String = text.chars().take(columns.saturating_sub(2)).collect();
    format!("{head}..")
}
